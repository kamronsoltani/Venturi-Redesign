#!/usr/bin/env python3
"""
setup_case.py -- create one Stage 1 OpenFOAM case (OpenFOAM 13, foamRun
incompressibleFluid) for a geometry, flow rate and mesh level.

Physics (Stage 1 setup)
  * steady, incompressible, single phase, water at 25 C (nu = 8.9e-7 m2/s;
    rho = 997 kg/m3 used only to convert kinematic pressure)
  * gravity +9.81 m/s2 along +x (flow direction, downward) via the
    buoyancyForce fvModel, so p includes the hydrostatic part
  * k-omega SST, wall-resolved (no wall functions): k = 0, nut = 0 and
    omega = 10*6*nu/(beta1*y1^2) (Menter 1994) on the wall, y1 = distance
    of the wall-adjacent cell centre (from mesh_info.json)
  * inlet: fixed flow rate (uniform velocity Q/A_inlet), p fixedFluxPressure
  * outlet: atmospheric, p totalPressure p0 = 0 (= static 0 for outflow),
    U pressureInletOutletVelocity (backflow-safe)
  * wall: no slip

Usage
  python3 setup_case.py --geom current --q 25 [--level medium] [--case <dir>]
Default case dir: cfd/<geom>/Q<q>  (+ _<level> when level != medium)
"""
import argparse
import math
import os
import shutil

import make_wedge_mesh as mwm

HERE = os.path.dirname(os.path.abspath(__file__))
NU = 8.9e-7
RHO = 997.0
G = 9.81
BETA1 = 0.075
TURB_INTENSITY = 0.05           # inlet turbulence intensity
MIXING_LENGTH_FRAC = 0.07       # inlet mixing length / inlet diameter
END_ITER = 4000   # user-approved 2026-11-12: Q25 medium quantities flat by ~2000 it


def hdr(cls, loc, obj):
    return ("/*--------------------------------*- C++ -*----------------------------------*\\\n"
            "  OpenFOAM 13 | generated by cfd/setup_case.py\n"
            "\\*---------------------------------------------------------------------------*/\n"
            f"FoamFile\n{{\n    format      ascii;\n    class       {cls};\n"
            f'    location    "{loc}";\n    object      {obj};\n}}\n\n')


def write(case, rel, text):
    path = os.path.join(case, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as fh:
        fh.write(text)


def field(case, name, cls, dims, internal, bcs):
    body = hdr(cls, "0", name) + f"dimensions      {dims};\n\ninternalField   {internal};\n\nboundaryField\n{{\n"
    for patch, spec in bcs.items():
        body += f"    {patch}\n    {{\n" + "".join(f"        {l}\n" for l in spec) + "    }\n"
    body += "}\n"
    write(case, os.path.join("0", name), body)


def setup(geom, q_lpm, level="medium", case=None, init="uniform"):
    if case is None:
        sub = f"Q{q_lpm:g}" + ("" if level == "medium" else f"_{level}")
        case = os.path.join(HERE, geom, sub)
    if os.path.isdir(case):
        shutil.rmtree(case)
    os.makedirs(case)
    info = mwm.build_mesh(geom, case, level)

    Rin = info["inlet_radius_mm"] * 1e-3
    Q = q_lpm / 60000.0
    Uin = Q / (math.pi * Rin ** 2)
    k_in = 1.5 * (TURB_INTENSITY * Uin) ** 2
    L_mix = MIXING_LENGTH_FRAC * 2 * Rin
    om_in = math.sqrt(k_in) / (0.09 ** 0.25 * L_mix)
    omega_wall = [10 * 6 * NU / (BETA1 * y ** 2) for y in info["wall_y1_m"]]
    om_list = "nonuniform List<scalar> %d\n(\n%s\n)" % (
        len(omega_wall), "\n".join(f"{w:.6g}" for w in omega_wall))
    wedge = ["type            wedge;"]

    # ------------------------------------------------------------ 0/
    if init == "plug":
        # initial guess only: axial plug flow Q/A(z) in every column (continuity-
        # consistent); converged steady result does not depend on it. Used where
        # the uniform start diverges (26-30 mm exits).
        zn, Rn, NR = info["z_nodes_mm"], info["R_nodes_mm"], info["NR"]
        vals = []
        for i in range(len(zn) - 1):
            Rm = 0.5 * (Rn[i] + Rn[i + 1]) * 1e-3
            vals += [f"({Q / (math.pi * Rm ** 2):.6g} 0 0)"] * NR
        U_internal = f"nonuniform List<vector> {len(vals)}\n(\n" + "\n".join(vals) + "\n)"
    else:
        U_internal = f"uniform ({Uin:.6g} 0 0)"
    field(case, "U", "volVectorField", "[0 1 -1 0 0 0 0]", U_internal, {
        "inlet": ["type            flowRateInletVelocity;",
                  f"meanVelocity    {Uin:.8g};   // Q = {q_lpm:g} L/min over the full inlet area",
                  "value           uniform (0 0 0);"],
        "outlet": ["type            pressureInletOutletVelocity;", "value           uniform (0 0 0);"],
        "wall": ["type            noSlip;"],
        "front": wedge, "back": wedge})
    field(case, "p", "volScalarField", "[0 2 -2 0 0 0 0]", "uniform 0", {
        "inlet": ["type            fixedFluxPressure;", "value           uniform 0;"],
        "outlet": ["type            totalPressure;", "p0              uniform 0;", "value           uniform 0;"],
        "wall": ["type            fixedFluxPressure;", "value           uniform 0;"],
        "front": wedge, "back": wedge})
    field(case, "k", "volScalarField", "[0 2 -2 0 0 0 0]", f"uniform {k_in:.6g}", {
        "inlet": ["type            turbulentIntensityKineticEnergyInlet;",
                  f"intensity       {TURB_INTENSITY};", f"value           uniform {k_in:.6g};"],
        "outlet": ["type            inletOutlet;", f"inletValue      uniform {k_in:.6g};",
                   f"value           uniform {k_in:.6g};"],
        "wall": ["type            fixedValue;", "value           uniform 0;"],
        "front": wedge, "back": wedge})
    field(case, "omega", "volScalarField", "[0 0 -1 0 0 0 0]", f"uniform {om_in:.6g}", {
        "inlet": ["type            turbulentMixingLengthFrequencyInlet;",
                  f"mixingLength    {L_mix:.6g};", f"value           uniform {om_in:.6g};"],
        "outlet": ["type            inletOutlet;", f"inletValue      uniform {om_in:.6g};",
                   f"value           uniform {om_in:.6g};"],
        "wall": ["type            fixedValue;   // Menter: 10*6*nu/(beta1*y1^2)",
                 f"value           {om_list};"],
        "front": wedge, "back": wedge})
    field(case, "nut", "volScalarField", "[0 2 -1 0 0 0 0]", "uniform 0", {
        "inlet": ["type            calculated;", "value           uniform 0;"],
        "outlet": ["type            calculated;", "value           uniform 0;"],
        "wall": ["type            fixedValue;", "value           uniform 0;"],
        "front": wedge, "back": wedge})

    # ------------------------------------------------------------ constant/
    write(case, "constant/physicalProperties", hdr("dictionary", "constant", "physicalProperties") +
          f"viscosityModel  constant;\n\nnu              {NU};   // water 25 C (rho = {RHO:g})\n")
    write(case, "constant/momentumTransport", hdr("dictionary", "constant", "momentumTransport") +
          "simulationType  RAS;\n\nRAS\n{\n    model           kOmegaSST;\n"
          "    turbulence      on;\n    viscosityModel  Newtonian;\n}\n")
    write(case, "constant/g", hdr("uniformDimensionedVectorField", "constant", "g") +
          f"dimensions      [0 1 -2 0 0 0 0];\nvalue           ({G} 0 0);   // along the flow (downward)\n")
    write(case, "constant/fvModels", hdr("dictionary", "constant", "fvModels") +
          "buoyancyForce\n{\n    type            buoyancyForce;\n    U               U;\n}\n")

    # ------------------------------------------------------------ system/
    write(case, "system/controlDict", hdr("dictionary", "system", "controlDict") + f"""\
solver          incompressibleFluid;

startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {END_ITER};
deltaT          1;

writeControl    timeStep;
writeInterval   1000;
purgeWrite      1;
writeFormat     ascii;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;

functions
{{
    #includeFunc residuals(p, U, k, omega)
    #includeFunc patchAverage(name=inletAvg, patch=inlet, fields=(p U))
    #includeFunc patchFlowRate(name=inletFlow, patch=inlet)
    #includeFunc patchFlowRate(name=outletFlow, patch=outlet)
    #includeFunc yPlus
    #includeFunc wallShearStress
}}
""")
    write(case, "system/fvSchemes", hdr("dictionary", "system", "fvSchemes") + """\
ddtSchemes
{
    default         steadyState;
}

gradSchemes
{
    default         Gauss linear;
    grad(k)         cellLimited Gauss linear 1;
    grad(omega)     cellLimited Gauss linear 1;
}

divSchemes
{
    default         none;
    div(phi,U)      bounded Gauss linearUpwind grad(U);
    div(phi,k)      bounded Gauss limitedLinear 1;
    div(phi,omega)  bounded Gauss limitedLinear 1;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}

laplacianSchemes
{
    default         Gauss linear corrected;
}

interpolationSchemes
{
    default         linear;
}

snGradSchemes
{
    default         corrected;
}

wallDist
{
    method          meshWave;
}
""")
    write(case, "system/fvSolution", hdr("dictionary", "system", "fvSolution") + """\
solvers
{
    p
    {
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       1e-09;
        relTol          0.05;
    }

    "(U|k|omega)"
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-11;
        relTol          0.1;
    }
}

SIMPLE
{
    nNonOrthogonalCorrectors 0;
    consistent      yes;

    residualControl
    {
        p               1e-6;
        U               1e-7;
        "(k|omega)"     1e-7;
    }
}

relaxationFactors
{
    equations
    {
        U               0.9;
        "(k|omega)"     0.7;
    }
}
""")
    with open(os.path.join(case, "case_info.txt"), "w", newline="\n") as fh:
        fh.write(f"geometry {geom}\nQ_lpm {q_lpm:g}\nlevel {level}\nU_inlet_m_s {Uin:.6g}\n"
                 f"k_inlet {k_in:.6g}\nomega_inlet {om_in:.6g}\nmixing_length_m {L_mix:.6g}\ninitial_U {init}\n")
    print(f"case {case}: {info['n_cells']} cells, U_in = {Uin:.4f} m/s")
    return case


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--geom", required=True)
    ap.add_argument("--q", type=float, required=True, help="flow rate, L/min")
    ap.add_argument("--level", default="medium", choices=sorted(mwm.LEVELS))
    ap.add_argument("--case", default=None)
    ap.add_argument("--init", default="uniform", choices=["uniform", "plug"],
                    help="initial U: uniform inlet velocity, or plug flow Q/A(z)")
    a = ap.parse_args()
    setup(a.geom, a.q, a.level, a.case, a.init)


if __name__ == "__main__":
    main()
